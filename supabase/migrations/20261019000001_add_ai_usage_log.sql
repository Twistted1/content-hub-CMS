-- `ai_usage_log` is the source of truth for "AI spend so far", read by
-- `_shared/aiBudget.ts` before every paid-API call in `content-pipeline`,
-- `novee-chat` and `generate-strategy`, and written by `recordAiUsage` after
-- each one.
--
-- It already exists in production, but it was created out-of-band in the
-- dashboard and NO migration ever created it — the same drift as
-- `project_settings`, `subscribers`, `articles` and `authors`. That matters more
-- here than for a purely cosmetic object, because of the failure mode: on a
-- fresh environment (a self-host, the disposable E2E project, or anyone running
-- this from the repo) the table would be missing, so
--   * `checkAiBudget` would read no rows and therefore always allow, and
--   * `recordAiUsage`'s insert would fail,
-- and the *only* spend protection in the product would quietly stop existing
-- while every test still passed. `aiBudget.ts` now logs those failures loudly
-- rather than swallowing them; this migration removes the failure entirely.

CREATE TABLE IF NOT EXISTS public.ai_usage_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  -- Which call site recorded it: 'content-pipeline' | 'novee-chat' | 'generate-strategy'.
  source text NOT NULL,
  cost_estimate numeric NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.ai_usage_log IS
  'One row per successful paid-AI call. Read by _shared/aiBudget.ts to enforce the instance-wide and per-user monthly limits. Written service-role only.';

-- The budget check sums the current calendar month, filtered per user for the
-- per-user cap, so both access paths need an index.
CREATE INDEX IF NOT EXISTS idx_ai_usage_log_created_at
  ON public.ai_usage_log (created_at);
CREATE INDEX IF NOT EXISTS idx_ai_usage_log_user_created_at
  ON public.ai_usage_log (user_id, created_at);

ALTER TABLE public.ai_usage_log ENABLE ROW LEVEL SECURITY;

-- Read-only for users, scoped to their own rows. There is deliberately NO insert
-- policy for `anon` or `authenticated`: only the edge functions write here, and
-- they use the service role, which bypasses RLS. Letting a browser insert would
-- let anyone forge their own (or anyone else's) spend records.
DROP POLICY IF EXISTS "Users can view own AI usage" ON public.ai_usage_log;
CREATE POLICY "Users can view own AI usage"
  ON public.ai_usage_log FOR SELECT TO authenticated
  USING (auth.uid() = user_id);

-- `(select auth.uid())` rather than a bare `auth.uid()`: this project already
-- fixed a project-wide perf sweep for re-evaluating auth.uid() per row, and a
-- new policy would otherwise reintroduce the `auth_rls_initplan` advisor warning.
DROP POLICY IF EXISTS "Admins can view all AI usage" ON public.ai_usage_log;
CREATE POLICY "Admins can view all AI usage"
  ON public.ai_usage_log FOR SELECT TO authenticated
  USING (public.has_role((select auth.uid()), 'admin'::app_role));

-- The per-user monthly cap the code reads, defaulting to the same 5 the code
-- falls back to. Guarded because `project_settings` has no `CREATE TABLE` in this
-- repository either (see docs/READINESS_GAP_ANALYSIS.md — that is still open), so
-- on a fresh database the table may genuinely not exist and an unguarded ALTER
-- would abort the whole migration run. Missing the column is survivable: the code
-- falls back to its default, whereas aborting takes every later migration with it.
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.tables
    WHERE table_schema = 'public' AND table_name = 'project_settings'
  ) THEN
    ALTER TABLE public.project_settings
      ADD COLUMN IF NOT EXISTS per_user_monthly_budget numeric NOT NULL DEFAULT 5;

    COMMENT ON COLUMN public.project_settings.per_user_monthly_budget IS
      'Per-user monthly AI spend cap, enforced by _shared/aiBudget.ts alongside monthly_openai_budget (the instance-wide ceiling).';
  ELSE
    RAISE NOTICE 'project_settings does not exist; skipping per_user_monthly_budget. The AI budget code falls back to its default of 5.';
  END IF;
END $$;
